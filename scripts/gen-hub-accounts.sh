#!/bin/sh
# Writes the hub's accounts: one for the cloud (fleet) and one per site.
#   usage: scripts/gen-hub-accounts.sh site1 site2 > config/hub-accounts.conf
#
# A site's leaf logs in to its own account. An account sees only what it
# imports, so each site can reach exactly this and nothing else:
#   its uplink stream is copied out   ($JS.<site>.API, $JS.FC.<site>-uplink, _fleet.copy.<site>)
#   its command consumer is pulled in (_fleet.api.CONSUMER.*, $JS.ACK.fleet-commands.<site>-commands)
set -eu
[ $# -ge 1 ] || { echo "usage: $0 site1 [site2 ...]" >&2; exit 1; }
for s in "$@"; do
  case $s in *[!a-z0-9]*|'') echo "bad site id: $s (use a-z, 0-9)" >&2; exit 1;; esac
done

echo "# Generated by scripts/gen-hub-accounts.sh $* -- do not edit."
echo "accounts {"
echo "  fleet {"
echo "    jetstream: enabled"
echo "    users: [ { user: cloud-app, password: \$CLOUD_APP_PASS } ]"
echo "    exports: ["
for s in "$@"; do cat <<E
      { service: "\$JS.API.CONSUMER.MSG.NEXT.fleet-commands.$s-commands", accounts: [$s], response_type: stream }
      { service: "\$JS.API.CONSUMER.INFO.fleet-commands.$s-commands", accounts: [$s] }
      { service: "\$JS.ACK.fleet-commands.$s-commands.>", accounts: [$s] }
E
done
echo "    ]"
echo "    imports: ["
for s in "$@"; do cat <<E
      { service: { account: $s, subject: "\$JS.$s.API.>" } }
      { service: { account: $s, subject: "\$JS.FC.$s-uplink.>" } }
      { stream:  { account: $s, subject: "_fleet.copy.$s.>" } }
E
done
echo "    ]"
echo "  }"
for s in "$@"; do cat <<E

  $s {
    users: [ { user: "CN=$s,O=fleet" } ]
    exports: [
      { service: "\$JS.$s.API.>", accounts: [fleet] }
      { service: "\$JS.FC.$s-uplink.>", accounts: [fleet] }
      { stream:  "_fleet.copy.$s.>", accounts: [fleet] }
    ]
    imports: [
      { service: { account: fleet, subject: "\$JS.API.CONSUMER.MSG.NEXT.fleet-commands.$s-commands" }, to: "_fleet.api.CONSUMER.MSG.NEXT.fleet-commands.$s-commands" }
      { service: { account: fleet, subject: "\$JS.API.CONSUMER.INFO.fleet-commands.$s-commands" }, to: "_fleet.api.CONSUMER.INFO.fleet-commands.$s-commands" }
      { service: { account: fleet, subject: "\$JS.ACK.fleet-commands.$s-commands.>" } }
    ]
  }
E
done
echo
echo "  system { users: [ { user: sys, password: \$SYS_PASS } ] }"
echo "}"
echo "system_account: system"
