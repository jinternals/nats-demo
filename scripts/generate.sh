#!/bin/sh
# Generates all per-site configuration from one list of site ids.
#   usage: scripts/generate.sh site1 site2 ...
# Writes config/generated/ (never edit by hand; `make up` re-runs this):
#   hub-accounts.conf             hub accounts: cloud, one per site, system
#   <site>.conf                   site server config
#   streams/<site>-outbox.json    site stream: events waiting to go to the cloud
#   streams/<site>-controller.json  the site's consumer on cloud-outbox
#   streams/cloud-inbox.json      cloud stream: events from all sites
#
# Naming: docs/naming.md. Forwarding rules (docs/guide.md):
#   up:   device.to.site.<device>.<type>  ->  site.to.cloud.<site>.<type>   (<site>-outbox transform)
#   down: cloud.to.site.<site>.command    ->  site controller               ->  site.to.device.<device>.command
set -eu
[ $# -ge 1 ] || { echo "usage: $0 site1 [site2 ...]" >&2; exit 1; }
for s in "$@"; do
  case $s in *[!a-z0-9-]*|''|-*) echo "bad site id: $s (use a-z, 0-9, -)" >&2; exit 1;; esac
done
out=config/generated
rm -rf "$out"; mkdir -p "$out/streams"

# ---------------------------------------------------------------- hub accounts
{
echo "# Generated by scripts/generate.sh $* -- do not edit."
echo "accounts {"
echo "  cloud {"
echo "    jetstream: enabled"
echo "    users: [ { user: cloud-app, password: \$CLOUD_APP_PASS, permissions: {"
echo "      # the cloud sends only cloud.to.site.*; reads everything via JetStream"
echo "      publish:   { allow: [ \"cloud.to.site.>\", \"\$JS.API.>\", \"\$JS.ACK.>\", \"_INBOX.>\" ] }"
echo "      subscribe: { allow: [ \"_INBOX.>\" ] }"
echo "    } } ]"
echo "    exports: ["
for s in "$@"; do cat <<E
      { service: "\$JS.API.CONSUMER.MSG.NEXT.cloud-outbox.$s-controller", accounts: [$s], response_type: stream }
      { service: "\$JS.API.CONSUMER.INFO.cloud-outbox.$s-controller", accounts: [$s] }
      { service: "\$JS.ACK.cloud-outbox.$s-controller.>", accounts: [$s] }
E
done
echo "    ]"
echo "    imports: ["
for s in "$@"; do cat <<E
      { service: { account: $s, subject: "\$JS.$s.API.>" } }
      { service: { account: $s, subject: "\$JS.FC.$s-outbox.>" } }
      { stream:  { account: $s, subject: "_edge.copy.$s.>" } }
E
done
echo "    ]"
echo "  }"
for s in "$@"; do cat <<E

  # $s: its leaf logs in here with its certificate (CN=$s,O=fleet)
  $s {
    users: [ { user: "CN=$s,O=fleet" } ]
    exports: [
      { service: "\$JS.$s.API.>", accounts: [cloud] }
      { service: "\$JS.FC.$s-outbox.>", accounts: [cloud] }
      { stream:  "_edge.copy.$s.>", accounts: [cloud] }
    ]
    imports: [
      { service: { account: cloud, subject: "\$JS.API.CONSUMER.MSG.NEXT.cloud-outbox.$s-controller" }, to: "_edge.api.CONSUMER.MSG.NEXT.cloud-outbox.$s-controller" }
      { service: { account: cloud, subject: "\$JS.API.CONSUMER.INFO.cloud-outbox.$s-controller" }, to: "_edge.api.CONSUMER.INFO.cloud-outbox.$s-controller" }
      { service: { account: cloud, subject: "\$JS.ACK.cloud-outbox.$s-controller.>" } }
    ]
  }
E
done
echo
echo "  system { users: [ { user: sys, password: \$SYS_PASS } ] }"
echo "}"
echo "system_account: system"
} > "$out/hub-accounts.conf"

# ---------------------------------------------------------------- per site
for s in "$@"; do
cat > "$out/$s.conf" <<E
# Generated by scripts/generate.sh -- do not edit. Site server for $s.
server_name: $s
listen: 0.0.0.0:4222
http: 0.0.0.0:8222

# Notice a dead WAN link within about a minute (default: 2m x 2 pings).
ping_interval: "20s"
ping_max: 2

jetstream {
  domain: $s
  store_dir: /data
  max_file_store: 20GB      # outbox size: event rate x the longest outage to survive
  sync_interval: always     # fsync every write; the default is every 2m
}

accounts {
  site {
    jetstream: enabled
    users: [
      # Devices: send device.to.site.<device>.<type>, receive site.to.device.<device>.<type>.
      { user: device, password: \$DEVICE_PASS, permissions: {
          publish:   { allow: [ "device.to.site.>" ] }
          subscribe: { allow: [ "site.to.device.>", "_INBOX.>" ] }
          allow_responses: true   # may reply to a command it received, nothing more
      }}
      # Site controller: pulls this site's commands from the cloud, sends them to devices.
      { user: site-controller, password: \$SITE_CONTROLLER_PASS, permissions: {
          publish: { allow: [
            "site.to.device.>"
            "_edge.api.CONSUMER.MSG.NEXT.cloud-outbox.$s-controller"
            "_edge.api.CONSUMER.INFO.cloud-outbox.$s-controller"
            "\$JS.ACK.cloud-outbox.$s-controller.>"
          ] }
          subscribe: { allow: [ "device.to.site.>", "_INBOX.>" ] }
      }}
      # Provisioning (creates $s-outbox). Not for apps.
      { user: site-ops, password: \$SITE_OPS_PASS }
    ]
  }
  system { users: [ { user: sys, password: \$SYS_PASS } ] }
}
system_account: system

leafnodes {
  reconnect: "5s"           # plus random jitter of up to 5s
  remotes: [
    {
      urls: [ "tls://cloud-hub:7422" ]
      account: site
      tls {
        ca_file:   /certs/ca.crt
        cert_file: /certs/$s.crt
        key_file:  /certs/$s.key
      }
      # HTTPS-only network: use urls: [ "wss://cloud-hub:443" ] instead, and
      # if traffic must go through a proxy, add AFTER the tls block:
      #   proxy { url: "http://proxy.example:3128" }
    }
  ]
}
E

# Up rule: device events are stored under the cloud-facing subject, without the device id.
cat > "$out/streams/$s-outbox.json" <<E
{
  "name": "$s-outbox",
  "subjects": [
    "device.to.site.*.telemetry",
    "device.to.site.*.health",
    "device.to.site.*.result"
  ],
  "subject_transform": {
    "src": "device.to.site.*.*",
    "dest": "site.to.cloud.$s.{{wildcard(2)}}"
  },
  "retention": "limits",
  "storage": "file",
  "num_replicas": 1,
  "max_age": 259200000000000,
  "max_bytes": 16106127360,
  "discard": "new",
  "duplicate_window": 120000000000
}
E

cat > "$out/streams/$s-controller.json" <<E
{
  "durable_name": "$s-controller",
  "filter_subject": "cloud.to.site.$s.>",
  "deliver_policy": "all",
  "ack_policy": "explicit",
  "ack_wait": 30000000000,
  "max_deliver": -1,
  "max_ack_pending": 100
}
E
done

# ---------------------------------------------------------------- cloud-inbox
{
echo "{"
echo '  "name": "cloud-inbox",'
echo '  "retention": "limits",'
echo '  "storage": "file",'
echo '  "num_replicas": 3,'
echo '  "max_age": 604800000000000,'
echo '  "duplicate_window": 120000000000,'
echo '  "sources": ['
n=0
for s in "$@"; do
  n=$((n + 1)); sep=","; [ $n -eq $# ] && sep=""
  echo "    { \"name\": \"$s-outbox\", \"external\": { \"api\": \"\$JS.$s.API\", \"deliver\": \"_edge.copy.$s\" } }$sep"
done
echo '  ]'
echo "}"
} > "$out/streams/cloud-inbox.json"

echo "generated $out for: $*"
