#!/bin/sh
# Generates Pattern C (Cloud Bridge -> Site NATS, no Cloud NATS hub) config
# from one list of site ids.
#   usage: scripts/generate.sh site1 site2 ...
# Writes config/generated/ (never edit by hand; `make up` re-runs this):
#   <site>.conf                     site NATS server config (reachable over VPN/WAN)
#   bridge/<site>-nats-kafka.conf   cloud-side nats-io/nats-kafka bridge config for <site>
#   streams/<site>-outbox.json      site stream: device events waiting for Cloud Kafka
#   streams/<site>-inbox.json       site stream: commands received from Cloud Kafka
#   streams/<site>-controller.json  site controller consumer on <site>-inbox
set -eu
[ $# -ge 1 ] || { echo "usage: $0 site1 [site2 ...]" >&2; exit 1; }
for s in "$@"; do
  case $s in *[!a-z0-9-]*|''|-*) echo "bad site id: $s (use a-z, 0-9, -)" >&2; exit 1;; esac
done
out=config/generated
rm -rf "$out"; mkdir -p "$out/streams" "$out/bridge"
bridge_pass="${KAFKA_BRIDGE_PASS:-dev-bridge}"

for s in "$@"; do
# ---------------------------------------------------------------- site NATS server
cat > "$out/$s.conf" <<E
# Generated by scripts/generate-direct.sh -- do not edit.
# Pattern B (Direct Site-to-Kafka): standalone site NATS server for $s.
server_name: $s
listen: 0.0.0.0:4222
http: 0.0.0.0:8222

jetstream {
  domain: $s
  store_dir: /data
  max_file_store: 20GB      # outbox size: event rate x longest WAN outage
  sync_interval: always     # fsync every write
}

accounts {
  site {
    jetstream: enabled
    users: [
      # Devices: publish device.to.site.<device>.<type>, receive site.to.device.<device>.command.
      { user: device, password: \$DEVICE_PASS, permissions: {
          publish:   { allow: [ "device.to.site.>" ] }
          subscribe: { allow: [ "site.to.device.>", "_INBOX.>" ] }
          allow_responses: true
      }}
      # Site controller: pulls commands locally from $s-inbox, dispatches to devices.
      { user: site-controller, password: \$SITE_CONTROLLER_PASS, permissions: {
          publish: { allow: [
            "site.to.device.>"
            "\$JS.API.CONSUMER.MSG.NEXT.$s-inbox.$s-controller"
            "\$JS.API.CONSUMER.INFO.$s-inbox.$s-controller"
            "\$JS.ACK.$s-inbox.$s-controller.>"
          ] }
          subscribe: { allow: [ "device.to.site.>", "_INBOX.>" ] }
      }}
      # Local nats-kafka bridge: reads $s-outbox -> Cloud Kafka; writes Cloud Kafka -> $s-inbox.
      { user: kafka-bridge, password: \$KAFKA_BRIDGE_PASS, permissions: {
          publish: { allow: [
            "cloud.to.site.$s.>"
            "\$JS.API.STREAM.NAMES"
            "\$JS.API.STREAM.INFO.$s-outbox"
            "\$JS.API.CONSUMER.*.$s-outbox.>"
            "\$JS.API.CONSUMER.DURABLE.CREATE.$s-outbox.>"
            "\$JS.ACK.$s-outbox.>"
          ] }
          subscribe: { allow: [ "_INBOX.>" ] }
      }}
      # Provisioning (creates $s-outbox, $s-inbox, $s-controller). Not for apps.
      { user: site-ops, password: \$SITE_OPS_PASS }
    ]
  }
  system { users: [ { user: sys, password: \$SYS_PASS } ] }
}
system_account: system
E

# ---------------------------------------------------------------- streams & consumer
cat > "$out/streams/$s-outbox.json" <<E
{
  "name": "$s-outbox",
  "subjects": [
    "device.to.site.*.telemetry",
    "device.to.site.*.health",
    "device.to.site.*.result"
  ],
  "subject_transform": {
    "src": "device.to.site.*.*",
    "dest": "site.to.cloud.$s.{{wildcard(2)}}"
  },
  "retention": "limits",
  "storage": "file",
  "num_replicas": 1,
  "max_age": 259200000000000,
  "max_bytes": 16106127360,
  "discard": "new",
  "duplicate_window": 120000000000
}
E

cat > "$out/streams/$s-inbox.json" <<E
{
  "name": "$s-inbox",
  "subjects": ["cloud.to.site.$s.*"],
  "retention": "workqueue",
  "storage": "file",
  "num_replicas": 1,
  "max_age": 3600000000000,
  "allow_msg_ttl": true,
  "duplicate_window": 900000000000
}
E

cat > "$out/streams/$s-controller.json" <<E
{
  "durable_name": "$s-controller",
  "filter_subject": "cloud.to.site.$s.>",
  "deliver_policy": "all",
  "ack_policy": "explicit",
  "ack_wait": 30000000000,
  "max_deliver": -1,
  "max_ack_pending": 100
}
E

# ---------------------------------------------------------------- per-site nats-kafka bridge
{
cat <<E
# Generated by scripts/generate-direct.sh -- do not edit.
# Pattern B: local nats-kafka bridge at $s talking directly to Cloud Kafka over WAN.
reconnectinterval: 5000
connecttimeout: 5000

logging: {
  time: true
  debug: false
  trace: false
  colors: false
  pid: false
}

monitoring: {
  httphost: "0.0.0.0"
  httpport: 8222
}

nats: {
  servers: ["nats://kafka-bridge:${bridge_pass}@$s:4222"]
  connecttimeout: 5000
  reconnectwait: 2000
  maxreconnects: -1
}

connect: [
  {
    type: "KafkaToJetStream"
    id: "down-$s-command"
    brokers: ["kafka:9092"]
    topic: "cloud.to.site.$s.command"
    groupid: "kafka-bridge-$s"
    subject: "cloud.to.site.$s.command"
  }
E
for typ in telemetry health result; do cat <<E
  {
    type: "JetStreamToKafka"
    id: "up-$s-$typ"
    brokers: ["kafka:9092"]
    topic: "site.to.cloud.$typ"
    stream: "$s-outbox"
    subject: "site.to.cloud.$s.$typ"
    durablename: "kafka-bridge-$s-$typ"
    keytype: "fixed"
    keyvalue: "$s"
  }
E
done
echo "]"
} > "$out/bridge/$s-nats-kafka.conf"

done

echo "generated $out for: $*"
