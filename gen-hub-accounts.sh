#!/bin/bash
# Generate the hub's accounts file: one account per site.
#   usage: ./gen-hub-accounts.sh site1 site2 ... > config/hub-accounts.conf
#
# Why per-site accounts: a site's leaf binds to ITS OWN hub account, and an
# account only sees what it explicitly imports. Isolation is the account
# boundary rather than subject permissions on a shared account, so the reply
# subjects JetStream uses ($JSC.R.*, $JS.FC.*, _INBOX.*) are never visible
# to another site.
#
# What crosses each boundary (nothing else does):
#   SITEn -> FLEET  service $JS.siteN.API.>         hub sources SITEn_UPLINK
#                   service $JS.FC.SITEn_UPLINK.>   flow-control replies for it
#                   stream  fleet.deliver.siteN.>   the sourced messages
#   FLEET -> SITEn  service CONSUMER.MSG.NEXT / INFO for FLEET_COMMANDS.siteN-commands,
#                   imported as $JS.hub.API.* (NOT $JS.cloud.API.*: the hub
#                   intercepts its own domain prefix in every account and
#                   answers "JetStream not enabled for account" first)
#                   service $JS.ACK.FLEET_COMMANDS.siteN-commands.>
set -euo pipefail
[ $# -ge 1 ] || { echo "usage: $0 site1 [site2 ...]" >&2; exit 1; }
for s in "$@"; do [[ $s =~ ^[a-z0-9]+$ ]] || { echo "bad site id: $s" >&2; exit 1; }; done
up() { tr '[:lower:]' '[:upper:]' <<<"$1"; }

echo "# GENERATED by gen-hub-accounts.sh $* -- do not edit by hand"
echo "accounts {"
echo "  FLEET {"
echo "    jetstream: enabled"
echo "    users: [ { user: cloud-app, password: \$CLOUD_APP_PASS } ]"
echo "    exports: ["
for s in "$@"; do S=$(up "$s"); cat <<E
      { service: "\$JS.API.CONSUMER.MSG.NEXT.FLEET_COMMANDS.$s-commands", accounts: [$S], response_type: stream }
      { service: "\$JS.API.CONSUMER.INFO.FLEET_COMMANDS.$s-commands", accounts: [$S] }
      { service: "\$JS.ACK.FLEET_COMMANDS.$s-commands.>", accounts: [$S] }
E
done
echo "    ]"
echo "    imports: ["
for s in "$@"; do S=$(up "$s"); cat <<E
      { service: { account: $S, subject: "\$JS.$s.API.>" } }
      { service: { account: $S, subject: "\$JS.FC.${S}_UPLINK.>" } }
      { stream:  { account: $S, subject: "fleet.deliver.$s.>" } }
E
done
echo "    ]"
echo "  }"
for s in "$@"; do S=$(up "$s"); cat <<E

  # ---- $s: its leaf binds here via its client cert ----
  $S {
    users: [ { user: "CN=leaf-$s,O=fleet" } ]
    exports: [
      { service: "\$JS.$s.API.>", accounts: [FLEET] }
      { service: "\$JS.FC.${S}_UPLINK.>", accounts: [FLEET] }
      { stream:  "fleet.deliver.$s.>", accounts: [FLEET] }
    ]
    imports: [
      { service: { account: FLEET, subject: "\$JS.API.CONSUMER.MSG.NEXT.FLEET_COMMANDS.$s-commands" }, to: "\$JS.hub.API.CONSUMER.MSG.NEXT.FLEET_COMMANDS.$s-commands" }
      { service: { account: FLEET, subject: "\$JS.API.CONSUMER.INFO.FLEET_COMMANDS.$s-commands" }, to: "\$JS.hub.API.CONSUMER.INFO.FLEET_COMMANDS.$s-commands" }
      { service: { account: FLEET, subject: "\$JS.ACK.FLEET_COMMANDS.$s-commands.>" } }
    ]
  }
E
done
echo
echo "  SYS { users: [ { user: sys, password: \$SYS_PASS } ] }"
echo "}"
echo "system_account: SYS"
